
# pages/5_내가_만든_모델_소개.py
# 내가 만든 모델 소개
# 글 작성 및 평가 점수 정리 페이지
# 데이터 로딩, 파일 저장, 외부 전송 기능 없음

import streamlit as st
import pandas as pd


st.title("📝 내가 만든 모델 소개")

st.write(
    "앞 페이지에서 확인한 데이터와 모델의 결과를 바탕으로 "
    "내가 만든 모델을 소개해 보세요."
)

st.caption(
    "이 페이지는 직접 내용을 작성하는 서식입니다. "
    "데이터를 불러오거나 작성 내용을 파일로 저장하지 않습니다."
)


# --------------------------------------------------
# 작성할 질문과 안내 문구
# --------------------------------------------------

질문목록 = [
    {
        "질문": "무슨 데이터입니까",
        "안내": (
            "어떤 데이터를 사용했나요? 데이터에는 몇 명의 기록이 있으며, "
            "어떤 정보가 들어 있나요? 데이터의 출처도 적어 보세요."
        ),
    },
    {
        "질문": "무엇을 보고 맞힙니까",
        "안내": (
            "모델이 예측할 때 사용하는 속성은 무엇인가요? "
            "어떤 정보를 바탕으로 결과를 예측하는지 적어 보세요."
        ),
    },
    {
        "질문": "무엇을 고쳤습니까",
        "안내": (
            "데이터 전처리 과정에서 무엇을 바꾸었나요? "
            "결측값 처리 등 수정한 내용과 그 이유를 적어 보세요."
        ),
    },
    {
        "질문": "이 모델을 검진센터가 사용해도 됩니까",
        "안내": (
            "사용해도 되는지 자신의 판단을 적어 보세요. "
            "정확도뿐 아니라 놓친 환자, 잘못 양성으로 예측한 사람, "
            "실제 의료 현장에서 필요한 검증도 고려해 보세요."
        ),
    },
    {
        "질문": "이 모델이 못 하는 것 한 가지",
        "안내": (
            "현재 모델이 해결하지 못하는 문제나 한계를 한 가지 이상 적어 보세요."
        ),
    },
]


# --------------------------------------------------
# 점수표 기본값
# --------------------------------------------------

점수항목 = [
    "정확도",
    "재현율",
    "F1",
    "찾아낸 환자",
    "헛짚은 사람",
]

점수표키 = "모델소개_점수표"

if 점수표키 not in st.session_state:
    st.session_state[점수표키] = pd.DataFrame({
        "항목": 점수항목,
        "고치기 전": [""] * len(점수항목),
        "고친 뒤": [""] * len(점수항목),
    })


# --------------------------------------------------
# 탭 구성
# --------------------------------------------------

작성탭, 한장보기탭 = st.tabs([
    "✏️ ① 채워 넣기",
    "📄 ② 한 장으로 보기",
])


# ==================================================
# 탭 1: 채워 넣기
# ==================================================

with 작성탭:

    st.subheader("1. 내가 만든 모델 설명")

    for 번호, 항목 in enumerate(질문목록, start=1):

        st.text_area(
            항목["질문"],
            placeholder=항목["안내"],
            height=130,
            key=f"모델소개_글_{번호}",
        )

    st.divider()

    st.subheader("2. 고치기 전과 고친 뒤의 점수")

    st.write(
        "앞 페이지에서 확인한 평가 결과를 직접 옮겨 적으세요. "
        "이 표는 자동으로 점수를 계산하지 않습니다."
    )

    st.caption(
        "정확도·재현율·F1은 비율이나 점수로, "
        "찾아낸 환자와 헛짚은 사람은 인원수로 입력할 수 있습니다."
    )

    현재점수표 = st.session_state[점수표키]

    편집한점수표 = st.data_editor(
        현재점수표,
        width="stretch",
        hide_index=True,
        num_rows="fixed",
        disabled=["항목"],
        key="모델소개_점수표_편집기",
        column_config={
            "항목": st.column_config.TextColumn(
                "평가 항목",
                help="평가 항목 이름은 수정할 수 없습니다.",
            ),
            "고치기 전": st.column_config.TextColumn(
                "고치기 전",
                help="전처리 전의 평가 결과를 입력하세요.",
            ),
            "고친 뒤": st.column_config.TextColumn(
                "고친 뒤",
                help="전처리 후의 평가 결과를 입력하세요.",
            ),
        },
    )

    # 편집 내용을 현재 앱 세션에서 유지합니다.
    st.session_state[점수표키] = 편집한점수표.copy()

    st.info(
        "입력한 내용은 현재 앱 세션에서 화면에 표시하기 위해 유지됩니다. "
        "이 페이지에는 다운로드, 파일 저장, 외부 전송 기능이 없습니다."
    )


# ==================================================
# 탭 2: 한 장으로 보기
# ==================================================

with 한장보기탭:

    st.subheader("📝 내가 만든 모델 소개")

    st.write(
        "작성 탭에 입력한 글과 점수표를 아래에 차례대로 모았습니다."
    )

    st.divider()

    # ----------------------------------------------
    # 작성한 글 표시
    # ----------------------------------------------

    for 번호, 항목 in enumerate(질문목록, start=1):

        st.markdown(f"### {번호}. {항목['질문']}")

        답변 = st.session_state.get(
            f"모델소개_글_{번호}",
            "",
        )

        if 답변 and 답변.strip():
            st.markdown(답변)
        else:
            st.caption("아직 적지 않았습니다.")

        st.divider()

    # ----------------------------------------------
    # 점수표 표시
    # ----------------------------------------------

    st.markdown("### 6. 고치기 전과 고친 뒤의 점수")

    현재점수표 = st.session_state.get(
        점수표키,
        pd.DataFrame({
            "항목": 점수항목,
            "고치기 전": [""] * len(점수항목),
            "고친 뒤": [""] * len(점수항목),
        }),
    )

    st.table(현재점수표.set_index("항목"))

    # ----------------------------------------------
    # 작성 상태 안내
    # ----------------------------------------------

    미작성글수 = sum(
        not st.session_state.get(
            f"모델소개_글_{번호}",
            "",
        ).strip()
        for 번호 in range(1, len(질문목록) + 1)
    )

    미작성점수수 = sum(
        not str(행["고치기 전"]).strip()
        or not str(행["고친 뒤"]).strip()
        for _, 행 in 현재점수표.iterrows()
    )

    st.divider()

    if 미작성글수 == 0 and 미작성점수수 == 0:
        st.success("모든 글과 점수 칸을 작성했습니다.")
    else:
        st.caption(
            f"아직 작성하지 않은 글: {미작성글수}개 · "
            f"고치기 전 또는 고친 뒤가 비어 있는 점수 항목: "
            f"{미작성점수수}개"
        )

    st.caption(
        "이 화면은 작성 내용을 모아 보여 주는 기능입니다. "
        "파일로 저장하거나 다른 곳으로 전송하지 않습니다."
    )
